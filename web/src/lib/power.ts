/**
 * First-order power model for a polar lunar site.
 *
 * Deliberately simple and explicitly labelled as such in the UI: solar constant,
 * cosine incidence, cell efficiency and a derate. No thermal derating, no dust
 * accumulation curve, no eclipse transients.
 */

export const SOLAR_CONSTANT = 1361; // W/m^2 at 1 AU
export const CELL_EFFICIENCY = 0.28; // space-grade triple junction, conservative
export const SYSTEM_DERATE = 0.9; // wiring, dust, thermal, MPPT losses

export type ArrayMode = "horizontal" | "tracking" | "vertical";

/**
 * Instantaneous array output per square metre of panel.
 * - horizontal: cos(zenith) = sin(elevation); near-useless at the pole where the
 *   Sun never rises above ~1.5 deg, which is exactly the design lesson.
 * - tracking: panel normal to the Sun (two-axis), the best case.
 * - vertical: fixed vertical panels split equally over four faces (N, E, S, W), the
 *   way most polar landers are built; at any moment at most two faces see the Sun,
 *   so a square metre of total panel gives 25-35% of a Sun-tracking one.
 */
export function arrayPowerPerM2(sunElevDeg: number, lit: boolean, mode: ArrayMode, sunAzDeg = 0): number {
  if (!lit) return 0;
  const el = (sunElevDeg * Math.PI) / 180;
  let cosIncidence = 1;
  if (mode === "horizontal") cosIncidence = Math.max(0, Math.sin(el));
  else if (mode === "vertical") {
    const az = (sunAzDeg * Math.PI) / 180;
    cosIncidence = (Math.max(0, Math.cos(el)) * (Math.abs(Math.cos(az)) + Math.abs(Math.sin(az)))) / 4;
  }
  return SOLAR_CONSTANT * cosIncidence * CELL_EFFICIENCY * SYSTEM_DERATE;
}

/** Wh generated by `areaM2` over a sample series with `stepMin` spacing. */
export function energyWh(
  samples: { sunElev: number; lit: boolean; sunAz?: number }[],
  stepMin: number,
  mode: ArrayMode,
  areaM2: number
): number {
  let wh = 0;
  for (const s of samples) wh += arrayPowerPerM2(s.sunElev, s.lit, mode, s.sunAz) * areaM2 * (stepMin / 60);
  return wh;
}

/** Battery needed to ride through `darkHours` at `loadW`, with a depth-of-discharge limit. */
export function batteryWh(darkHours: number, loadW: number, dod = 0.8): number {
  return (darkHours * loadW) / dod;
}

export type LanderSpec = {
  /** continuous electrical load, W */
  loadW: number;
  /** solar array area, m^2 */
  arrayM2: number;
  /** battery capacity, Wh */
  batteryWh: number;
  /** usable depth of discharge, 0..1 */
  dod: number;
  /** extra load while the lander is in shadow (survival heaters), W */
  heaterW?: number;
};

export type MissionResult = {
  survives: boolean;
  /** first sample time at which the usable battery is empty, or null */
  lostAt: number | null;
  /** lowest usable state of charge reached, % */
  minSocPct: number;
  /** usable state of charge at the end of the mission, % */
  endSocPct: number;
  /** state of charge per sample across the mission, % */
  soc: Float32Array;
};

/**
 * First-order energy balance through a mission: the battery starts full at landing,
 * charges from the array whenever the Sun clears the horizon, and powers a constant
 * load. The lander is lost when the usable charge reaches zero.
 */
export function simulateMission(
  samples: { t: number; sunElev: number; lit: boolean; sunAz?: number }[],
  startIdx: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec
): MissionResult {
  const usable = Math.max(1, spec.batteryWh * spec.dod);
  const stepH = stepMin / 60;
  const end = Math.min(samples.length, startIdx + steps);
  const soc = new Float32Array(Math.max(0, end - startIdx));
  let e = usable, min = usable, lostAt: number | null = null;
  for (let i = startIdx; i < end; i++) {
    const s = samples[i];
    e += (arrayPowerPerM2(s.sunElev, s.lit, mode, s.sunAz) * spec.arrayM2 - spec.loadW - (s.lit ? 0 : spec.heaterW ?? 0)) * stepH;
    if (e > usable) e = usable;
    if (e <= 0) {
      // A lander that runs flat in the dark is lost: it does not come back when the Sun returns.
      e = 0; min = 0; lostAt = s.t;
      break;
    }
    if (e < min) min = e;
    soc[i - startIdx] = (100 * e) / usable;
  }
  return {
    survives: lostAt === null && end - startIdx >= steps,
    lostAt,
    minSocPct: (100 * min) / usable,
    endSocPct: (100 * e) / usable,
    soc,
  };
}

/**
 * Landing "porkchop": for every landing time (every `stride` samples) run the same
 * battery balance as simulateMission and return the lowest usable charge (%),
 * or -1 if the lander is lost. Missions that would run past the data are NaN.
 */
export function porkchopRow(
  samples: { sunElev: number; lit: boolean; sunAz?: number }[],
  steps: number,
  stride: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec
): Float32Array {
  const n = samples.length;
  const stepH = stepMin / 60;
  const usable = Math.max(1, spec.batteryWh * spec.dod);
  // net energy per step, computed once per row
  const net = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const s = samples[i];
    net[i] = (arrayPowerPerM2(s.sunElev, s.lit, mode, s.sunAz) * spec.arrayM2 - spec.loadW - (s.lit ? 0 : spec.heaterW ?? 0)) * stepH;
  }
  const cols = Math.floor((n - 1) / stride) + 1;
  const out = new Float32Array(cols);
  for (let c = 0; c < cols; c++) {
    const start = c * stride;
    if (start + steps > n) { out[c] = NaN; continue; }
    let e = usable, min = usable, lost = false;
    for (let i = start; i < start + steps; i++) {
      e += net[i];
      if (e > usable) e = usable;
      if (e <= 0) { lost = true; break; }
      if (e < min) min = e;
    }
    out[c] = lost ? -1 : (100 * min) / usable;
  }
  return out;
}

/**
 * Smallest battery (Wh) and smallest panel area (m^2) with which this exact landing
 * survives, the other settings unchanged. Survival can only improve as either grows,
 * so a bisection finds the threshold. null: not reachable within the search range
 * (e.g. no panel size helps through a night longer than the battery lasts).
 */
export function sizeToSurvive(
  samples: { t: number; sunElev: number; lit: boolean; sunAz?: number }[],
  startIdx: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec
): { batteryWh: number | null; arrayM2: number | null } {
  const ok = (s: LanderSpec) => simulateMission(samples, startIdx, steps, stepMin, mode, s).survives;
  const search = (lo: number, hi: number, make: (v: number) => LanderSpec) => {
    if (!ok(make(hi))) return null;
    if (ok(make(lo))) return lo;
    for (let k = 0; k < 40 && hi - lo > hi * 0.002; k++) {
      const mid = (lo + hi) / 2;
      if (ok(make(mid))) hi = mid; else lo = mid;
    }
    return hi;
  };
  return {
    batteryWh: search(10, 1_000_000, (v) => ({ ...spec, batteryWh: v })),
    arrayM2: search(0.01, 500, (v) => ({ ...spec, arrayM2: v })),
  };
}

export function fmtEnergy(wh: number): string {
  if (wh >= 1000) return `${(wh / 1000).toFixed(1)} kWh`;
  return `${wh.toFixed(0)} Wh`;
}

export function fmtPower(w: number): string {
  return w >= 100 ? `${w.toFixed(0)} W` : `${w.toFixed(1)} W`;
}
