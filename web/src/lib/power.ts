/**
 * First-order power model for a polar lunar site.
 *
 * Deliberately simple and explicitly labelled as such in the UI: solar constant,
 * cosine incidence, cell efficiency and a derate. No thermal derating, no dust
 * accumulation curve, no eclipse transients.
 */

export const SOLAR_CONSTANT = 1361; // W/m^2 at 1 AU
export const CELL_EFFICIENCY = 0.28; // space-grade triple junction, conservative
export const SYSTEM_DERATE = 0.9; // wiring, dust, thermal, MPPT losses

export type ArrayMode = "horizontal" | "tracking";

/**
 * Instantaneous array output per square metre.
 * - horizontal: cos(zenith) = sin(elevation); near-useless at the pole where the
 *   Sun never rises above ~1.5 deg, which is exactly the design lesson.
 * - tracking: panel normal to the Sun (two-axis), the practical choice for polar
 *   arrays and vertical panel farms.
 */
export function arrayPowerPerM2(sunElevDeg: number, lit: boolean, mode: ArrayMode): number {
  if (!lit) return 0;
  const el = (sunElevDeg * Math.PI) / 180;
  const cosIncidence = mode === "horizontal" ? Math.max(0, Math.sin(el)) : 1;
  return SOLAR_CONSTANT * cosIncidence * CELL_EFFICIENCY * SYSTEM_DERATE;
}

/** Wh generated by `areaM2` over a sample series with `stepMin` spacing. */
export function energyWh(
  samples: { sunElev: number; lit: boolean }[],
  stepMin: number,
  mode: ArrayMode,
  areaM2: number
): number {
  let wh = 0;
  for (const s of samples) wh += arrayPowerPerM2(s.sunElev, s.lit, mode) * areaM2 * (stepMin / 60);
  return wh;
}

/** Battery needed to ride through `darkHours` at `loadW`, with a depth-of-discharge limit. */
export function batteryWh(darkHours: number, loadW: number, dod = 0.8): number {
  return (darkHours * loadW) / dod;
}

export function fmtEnergy(wh: number): string {
  if (wh >= 1000) return `${(wh / 1000).toFixed(1)} kWh`;
  return `${wh.toFixed(0)} Wh`;
}

export function fmtPower(w: number): string {
  return w >= 100 ? `${w.toFixed(0)} W` : `${w.toFixed(1)} W`;
}
