/**
 * First-order power model for a polar lunar site.
 *
 * Deliberately simple and explicitly labelled as such in the UI: solar constant,
 * cosine incidence, cell efficiency and a derate. No thermal derating, no dust
 * accumulation curve, no eclipse transients.
 */

export const SOLAR_CONSTANT = 1361; // W/m^2 at 1 AU
export const CELL_EFFICIENCY = 0.28; // space-grade triple junction, conservative
export const SYSTEM_DERATE = 0.9; // wiring, dust, thermal, MPPT losses

export type ArrayMode = "horizontal" | "tracking" | "vertical";

/**
 * Instantaneous array output per square metre of panel.
 * - horizontal: cos(zenith) = sin(elevation); near-useless at the pole where the
 *   Sun never rises above ~1.5 deg, which is exactly the design lesson.
 * - tracking: panel normal to the Sun (two-axis), the best case.
 * - vertical: fixed vertical panels split equally over four faces (N, E, S, W), the
 *   way most polar landers are built; at any moment at most two faces see the Sun,
 *   so a square metre of total panel gives 25-35% of a Sun-tracking one.
 */
export function arrayPowerPerM2(sunElevDeg: number, visible: boolean | number, mode: ArrayMode, sunAzDeg = 0): number {
  // visible: share of the solar disc above the local skyline (true = 1, false = 0)
  const frac = typeof visible === "number" ? Math.min(1, Math.max(0, visible)) : visible ? 1 : 0;
  if (frac <= 0) return 0;
  const el = (sunElevDeg * Math.PI) / 180;
  let cosIncidence = 1;
  if (mode === "horizontal") cosIncidence = Math.max(0, Math.sin(el));
  else if (mode === "vertical") {
    const az = (sunAzDeg * Math.PI) / 180;
    cosIncidence = (Math.max(0, Math.cos(el)) * (Math.abs(Math.cos(az)) + Math.abs(Math.sin(az)))) / 4;
  }
  return SOLAR_CONSTANT * frac * cosIncidence * CELL_EFFICIENCY * SYSTEM_DERATE;
}

/** Wh generated by `areaM2` over a sample series with `stepMin` spacing. */
export function energyWh(
  samples: { sunElev: number; lit: boolean; sunAz?: number; sunFrac?: number }[],
  stepMin: number,
  mode: ArrayMode,
  areaM2: number
): number {
  let wh = 0;
  for (const s of samples) wh += arrayPowerPerM2(s.sunElev, s.sunFrac ?? s.lit, mode, s.sunAz) * areaM2 * (stepMin / 60);
  return wh;
}

/** Battery needed to ride through `darkHours` at `loadW`, with a depth-of-discharge limit. */
export function batteryWh(darkHours: number, loadW: number, dod = 0.8): number {
  return (darkHours * loadW) / dod;
}

export type LanderSpec = {
  /** continuous electrical load, W */
  loadW: number;
  /** solar array area, m^2 */
  arrayM2: number;
  /** battery capacity, Wh */
  batteryWh: number;
  /** usable depth of discharge, 0..1 */
  dod: number;
  /** extra load while the lander is in shadow (survival heaters), W */
  heaterW?: number;
};

/** What the mission must achieve besides keeping power. */
export type MissionRequirements = {
  /** longest allowed stretch with no part of Earth above the skyline, hours; null = no requirement (autonomous or relay) */
  maxEarthOutageH?: number | null;
  /** battery charge at landing, % of usable (default 100) */
  initialSocPct?: number;
  /** charge that must never be touched, % of usable (default 0): falling to it counts as failing */
  reservePct?: number;
};

export type MissionSample = { t: number; sunElev: number; lit: boolean; sunAz?: number; sunFrac?: number; comm?: boolean };

export type MissionResult = {
  survives: boolean;
  /** which requirement failed first: the battery ran out, or Earth stayed hidden too long */
  failure: "battery" | "earth" | null;
  /** moment the usable battery reaches zero (interpolated inside the half-hour step), or null */
  lostAt: number | null;
  /** moment the Earth outage exceeded the allowed limit, or null */
  earthFailAt: number | null;
  /** lowest usable state of charge reached, % */
  minSocPct: number;
  /** usable state of charge at the end of the mission, % */
  endSocPct: number;
  /** longest stretch with Earth hidden during the mission, hours */
  longestEarthOutageH: number;
  /** state of charge at the end of each step across the mission, % */
  soc: Float32Array;
};

/** Heaters are needed until at least half of the Sun's disc is above the skyline. */
const HEATER_SUN_FRACTION = 0.5;

/**
 * The single mission evaluator behind every verdict, ranking, date grid, sizing answer and
 * export. Samples are taken as the start of each step. The battery starts at the given charge,
 * charges from the visible part of the solar disc, powers a constant load plus heaters while
 * less than half the Sun is up, and the lander is lost when the usable charge reaches zero
 * (the moment is interpolated within the step). A lost lander stays lost.
 */
export function simulateMission(
  samples: MissionSample[],
  startIdx: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec,
  req: MissionRequirements = {},
  trace = true
): MissionResult {
  const usable = Math.max(1, spec.batteryWh * spec.dod);
  const stepH = stepMin / 60, stepMs = stepMin * 60000;
  const end = Math.min(samples.length, startIdx + steps);
  const soc = new Float32Array(trace ? Math.max(0, end - startIdx) : 0);
  let e = (usable * (req.initialSocPct ?? 100)) / 100;
  let min = e, lostAt: number | null = null, earthFailAt: number | null = null;
  const floor = (usable * (req.reservePct ?? 0)) / 100;
  let outage = 0, longestOutage = 0;
  const maxOut = req.maxEarthOutageH ?? null;
  for (let i = startIdx; i < end; i++) {
    const s = samples[i];
    const frac = s.sunFrac ?? (s.lit ? 1 : 0);
    const watts = arrayPowerPerM2(s.sunElev, frac, mode, s.sunAz) * spec.arrayM2 - spec.loadW - (frac < HEATER_SUN_FRACTION ? spec.heaterW ?? 0 : 0);
    const next = e + watts * stepH;
    if (next <= floor) {
      // interpolate the moment the charge reaches the floor (zero, or the reserve) within this step
      lostAt = s.t + (watts < 0 ? Math.min(1, Math.max(0, e - floor) / (-watts * stepH)) : 1) * stepMs;
      e = floor; min = floor;
      break;
    }
    e = Math.min(usable, next);
    if (e < min) min = e;
    if (trace) soc[i - startIdx] = (100 * e) / usable;
    if (s.comm === false) {
      outage += stepH;
      if (outage > longestOutage) longestOutage = outage;
      if (maxOut !== null && earthFailAt === null && outage > maxOut) earthFailAt = s.t + stepMs;
    } else outage = 0;
  }
  const complete = end - startIdx >= steps;
  const failure: MissionResult["failure"] =
    lostAt !== null && (earthFailAt === null || lostAt <= earthFailAt) ? "battery" : earthFailAt !== null ? "earth" : null;
  return {
    survives: failure === null && complete,
    failure,
    lostAt,
    earthFailAt,
    minSocPct: (100 * min) / usable,
    endSocPct: (100 * e) / usable,
    longestEarthOutageH: longestOutage,
    soc,
  };
}

/**
 * Landing "porkchop": for every landing time (every `stride` samples) the same evaluation as
 * simulateMission. Each cell is the lowest usable charge (%) of a mission that meets every
 * requirement, -1 if it fails one, or NaN if the mission would run past the data.
 */
export function porkchopRow(
  samples: MissionSample[],
  steps: number,
  stride: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec,
  req: MissionRequirements = {}
): Float32Array {
  const cols = Math.floor((samples.length - 1) / stride) + 1;
  const out = new Float32Array(cols);
  for (let c = 0; c < cols; c++) {
    const start = c * stride;
    if (start + steps > samples.length) { out[c] = NaN; continue; }
    const r = simulateMission(samples, start, steps, stepMin, mode, spec, req, false);
    out[c] = r.survives ? r.minSocPct : -1;
  }
  return out;
}

/** Steps the app's inputs move in, so a recommendation is always a value the user can type. */
export const BATTERY_STEP_WH = 100;
export const ARRAY_STEP_M2 = 0.1;

/**
 * Two separate fixes for this exact landing, each keeping every other setting as it is:
 * the smallest battery that works, or the smallest panel area that works. Survival only
 * improves as either grows, so bisection finds the threshold; the answer is then rounded UP
 * to the input step and re-checked with the same evaluator, so the displayed value passes
 * when applied. null: not reachable in the search range, or the failure is not about power
 * (Earth hidden too long), which no battery or panel can fix.
 */
export function sizeToSurvive(
  samples: MissionSample[],
  startIdx: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec,
  req: MissionRequirements = {}
): { batteryWh: number | null; arrayM2: number | null; thresholdBatteryWh: number | null; thresholdArrayM2: number | null } {
  const ok = (s: LanderSpec) => simulateMission(samples, startIdx, steps, stepMin, mode, s, req, false).survives;
  const search = (lo: number, hi: number, make: (v: number) => LanderSpec) => {
    if (!ok(make(hi))) return null;
    if (ok(make(lo))) return lo;
    for (let k = 0; k < 50 && hi - lo > Math.max(1e-6, hi * 1e-5); k++) {
      const mid = (lo + hi) / 2;
      if (ok(make(mid))) hi = mid; else lo = mid;
    }
    return hi;
  };
  const roundUp = (v: number | null, step: number, make: (x: number) => LanderSpec) => {
    if (v === null) return null;
    // start at the step at or below the threshold and climb until the evaluator passes
    let x = Math.max(step, Math.floor(v / step) * step);
    for (let k = 0; k < 20 && !ok(make(x)); k++) x += step;
    return ok(make(x)) ? +x.toFixed(6) : null;
  };
  const bat = (v: number) => ({ ...spec, batteryWh: v });
  const arr = (v: number) => ({ ...spec, arrayM2: v });
  const tb = search(10, 1_000_000, bat);
  const ta = search(0.01, 500, arr);
  return {
    thresholdBatteryWh: tb,
    thresholdArrayM2: ta,
    batteryWh: roundUp(tb, BATTERY_STEP_WH, bat),
    arrayM2: roundUp(ta, ARRAY_STEP_M2, arr),
  };
}

export type StressCase = { id: string; label: string; result: MissionResult | null };

/** An alternative view of the terrain at the site (e.g. higher hills), as its own sample series. */
export type TerrainCase = { samples: MissionSample[]; label: string };

/**
 * The same landing under adverse assumptions, so a planner can see which assumption breaks
 * the plan. Every case uses the same requirements (battery reserve, Earth outage). These are
 * sensitivity cases chosen by us, not probabilities.
 */
export function stressTest(
  samples: MissionSample[],
  startIdx: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec,
  req: MissionRequirements = {},
  terrain: TerrainCase | null = null
): StressCase[] {
  const stepsPerH = 60 / stepMin;
  const run = (ser: MissionSample[], start: number, s: LanderSpec, r: MissionRequirements) =>
    start + steps <= ser.length ? simulateMission(ser, start, steps, stepMin, mode, s, r, false) : null;
  const cases: StressCase[] = [
    { id: "nominal", label: "As planned", result: run(samples, startIdx, spec, req) },
    { id: "slip6h", label: "Land 6 hours late", result: run(samples, startIdx + 6 * stepsPerH, spec, req) },
    { id: "slip1d", label: "Land 1 day late", result: run(samples, startIdx + 24 * stepsPerH, spec, req) },
    { id: "slip3d", label: "Land 3 days late", result: run(samples, startIdx + 72 * stepsPerH, spec, req) },
    { id: "panels", label: "Panels give 20% less", result: run(samples, startIdx, { ...spec, arrayM2: spec.arrayM2 * 0.8 }, req) },
    { id: "load", label: "Power use 20% higher", result: run(samples, startIdx, { ...spec, loadW: spec.loadW * 1.2 }, req) },
    { id: "charge", label: "Battery only 80% charged at landing", result: run(samples, startIdx, spec, { ...req, initialSocPct: 80 * (req.initialSocPct ?? 100) / 100 }) },
  ];
  if (terrain) cases.push({ id: "terrain", label: terrain.label, result: run(terrain.samples, startIdx, spec, req) });
  return cases;
}

/**
 * A plan passes only when every case was actually evaluated and survived. A case the data
 * cannot cover (null result) is unknown, never a pass.
 */
export function allCasesPass(cases: StressCase[]): boolean {
  return cases.length > 0 && cases.every((c) => c.result !== null && c.result.survives);
}

/**
 * Earliest start index in [from, last] whose mission meets every requirement, checking EVERY
 * step (no coarse scan), so a viable window shorter than any scan stride cannot be missed.
 */
export function earliestSurvivable(
  samples: MissionSample[],
  from: number,
  last: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec,
  req: MissionRequirements = {}
): number | null {
  for (let i = Math.max(0, from); i <= last && i + steps <= samples.length; i++)
    if (simulateMission(samples, i, steps, stepMin, mode, spec, req, false).survives) return i;
  return null;
}

/** The tested case that fails first (earliest failure), or null when every tested case passes. */
export function limitingCase(cases: StressCase[]): StressCase | null {
  const failing = cases.filter((c) => c.result && !c.result.survives);
  if (!failing.length) return null;
  const when = (c: StressCase) => (c.result!.failure === "earth" ? c.result!.earthFailAt : c.result!.lostAt) ?? Infinity;
  return failing.reduce((a, b) => (when(b) < when(a) ? b : a));
}

/**
 * Ways to make the plan pass EVERY tested case, each changing one thing: the earliest later
 * landing time, the smallest battery, or the smallest panel area. Each answer is rounded to an
 * input step and re-checked against all cases. null when that change cannot do it (for example
 * when Earth is hidden too long, which no battery or panel fixes).
 */
export function robustOptions(
  samples: MissionSample[],
  startIdx: number,
  steps: number,
  stepMin: number,
  mode: ArrayMode,
  spec: LanderSpec,
  req: MissionRequirements = {},
  terrain: TerrainCase | null = null,
  lastStartIdx = samples.length - steps
): { landIdx: number | null; batteryWh: number | null; arrayM2: number | null } {
  const allPass = (s: LanderSpec, start: number) => allCasesPass(stressTest(samples, start, steps, stepMin, mode, s, req, terrain));
  // later landing: every half-hour start is checked. The three late-arrival cases are the
  // nominal mission started later, so one pass over all starts screens them exactly; the
  // remaining cases run only where that screen passes.
  let landIdx: number | null = null;
  const stepsPerH = 60 / stepMin;
  const slips = [0, 6 * stepsPerH, 24 * stepsPerH, 72 * stepsPerH];
  const lastNom = Math.min(samples.length - steps, lastStartIdx + slips[3]);
  const nom = new Uint8Array(Math.max(0, lastNom + 1));
  for (let i = startIdx; i <= lastNom; i++) nom[i] = simulateMission(samples, i, steps, stepMin, mode, spec, req, false).survives ? 1 : 0;
  for (let i = startIdx; i <= lastStartIdx; i++) {
    if (!slips.every((d) => i + d <= lastNom && nom[i + d])) continue;
    if (allPass(spec, i)) { landIdx = i; break; }
  }
  const size = (lo: number, hi: number, step: number, make: (v: number) => LanderSpec) => {
    if (!allPass(make(hi), startIdx)) return null;
    for (let k = 0; k < 40 && hi - lo > step / 4; k++) {
      const mid = (lo + hi) / 2;
      if (allPass(make(mid), startIdx)) hi = mid; else lo = mid;
    }
    let x = Math.max(step, Math.floor(hi / step) * step);
    for (let k = 0; k < 20 && !allPass(make(x), startIdx); k++) x += step;
    return allPass(make(x), startIdx) ? +x.toFixed(6) : null;
  };
  return {
    landIdx,
    batteryWh: size(10, 1_000_000, BATTERY_STEP_WH, (v) => ({ ...spec, batteryWh: v })),
    arrayM2: size(0.01, 500, ARRAY_STEP_M2, (v) => ({ ...spec, arrayM2: v })),
  };
}

export function fmtEnergy(wh: number): string {
  if (wh >= 1000) return `${(wh / 1000).toFixed(1)} kWh`;
  return `${wh.toFixed(0)} Wh`;
}

export function fmtPower(w: number): string {
  return w >= 100 ? `${w.toFixed(0)} W` : `${w.toFixed(1)} W`;
}
